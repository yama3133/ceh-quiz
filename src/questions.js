function spreadOptions(options, questionNo) {
  const correct = options[0];
  const rotated = [...options];
  const target = (questionNo - 1) % 4;
  rotated[0] = options[target];
  rotated[target] = correct;
  return { options: rotated, answer: target };
}

const allQuestions = [];
let questionNo = 1;

for (const domain of domains) {
  for (let i = 0; i < domain.count; i++) {
    const topic = domain.topics[i % domain.topics.length];
    const cycle = Math.floor(i / domain.topics.length);
    const patternIdx = (i + cycle + domain.name.length) % patterns.length;
    const p = patterns[patternIdx](topic);
    const spread = spreadOptions(p.a, questionNo);
    allQuestions.push({
      id: questionNo,
      category: domain.name,
      question: p.q,
      options: spread.options,
      answer: spread.answer,
      explanation: p.exp,
    });
    questionNo++;
  }
}

